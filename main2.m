S = @(x) 2*pi*x(1)^2 + 2*pi*x(1)*x(2); % площадь поверхности банки (то что минимизируем)
V = @(x) pi*x(1)^2*x(2) - 1000; % объем банки (-1000 потому что для sqp нужно условие, которое должно стать нулем)

x0 = [6; 9]; % начальное приближение
lb = [0.1; 0.1]; % нижние границы
ub = [50; 50]; % верхние границы

[x_opt, S_min, info] = sqp(x0, S, V, [], lb, ub);

fprintf('Оптимальный радиус r = %.4f см\n', x_opt(1));
fprintf('Оптимальная высота h = %.4f см\n', x_opt(2));
fprintf('Минимальная площадь S = %.4f см^2\n', S_min);
fprintf('info = %d (101 = успех)\n', info);

