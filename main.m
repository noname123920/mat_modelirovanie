S0 = 10000; % начальный вклад
r = 0.1; % 10% годовых
c = 200; % упущенные возможности (рубли в год)

P = @(t) -(S0 * (1 + r).^t - c .* (t .^ 2)); % со знаком минус, потому что fminbnd ищет минимум

[t_opt, P_neg] = fminbnd(P, 0, 30);
P_max = -P_neg; % мы как бы "перевернули" функцию и минимум стал максимумом

fprintf('Оптимальный срок вклада: %.4f лет\n', t_opt);
fprintf('Чистая выгода от вклада: %.4f\n', P_max);
